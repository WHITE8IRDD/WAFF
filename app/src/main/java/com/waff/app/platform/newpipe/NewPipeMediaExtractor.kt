internal enum class ExtractedFormatKind { VIDEO_WITH_AUDIO, VIDEO_ONLY, AUDIO, IMAGE }

internal data class ExtractedFormat(
    val id: String,
    val kind: ExtractedFormatKind,
    val label: String,
    val url: String,
    val mimeType: String,
    val extension: String,
    val width: Int? = null,
    val height: Int? = null,
    val frameRate: Int? = null,
    val codec: String? = null,
    val bitrate: Int? = null,
    val language: String? = null,
    val fileSizeBytes: Long? = null,
    val headers: Map<String, String> = emptyMap()
)

internal data class ExtractedSubtitle(
    val languageTag: String,
    val languageName: String,
    val autoGenerated: Boolean,
    val url: String,
    val extension: String
)

internal data class ExtractedMediaInfo(
    val canonicalUrl: String,
    val title: String,
    val durationSeconds: Long,
    val thumbnailUrl: String?,
    val formats: List<ExtractedFormat>,
    val subtitles: List<ExtractedSubtitle>,
    val hashtags: List<String> = emptyList(),
    val supportsYtDlpMerge: Boolean = false
)

/** NewPipe Extractor adapter. It exposes upstream evidence without inventing formats or sizes. */
internal class NewPipeMediaExtractor {
    suspend fun extract(url: String): ExtractedMediaInfo = withContext(Dispatchers.IO) {
        require(supportsUrl(url)) { "This URL is not supported by the installed extractor." }
        val info = StreamInfo.getInfo(url)
        val streams = buildList {
            info.videoStreams.orEmpty().forEach { stream -> add(stream.toFormat()) }
            info.videoOnlyStreams.orEmpty().forEach { stream -> add(stream.toFormat()) }
            info.audioStreams.orEmpty().forEach { stream -> add(stream.toFormat()) }
        }.filter { it.url.isNotBlank() && it.mimeType.isNotBlank() }
            .distinctBy { it.id }
        val thumbnails = info.thumbnails.orEmpty()
        ExtractedMediaInfo(
            canonicalUrl = info.url,
            title = info.name,
            durationSeconds = info.duration,
            thumbnailUrl = thumbnails.maxByOrNull { it.height }?.url,
            formats = streams,
            subtitles = info.subtitles.orEmpty().mapNotNull { it.toSubtitleOrNull() }
        )
    }

    private fun VideoStream.toFormat(): ExtractedFormat {
        val format = format
        val kind = if (isVideoOnly) ExtractedFormatKind.VIDEO_ONLY else ExtractedFormatKind.VIDEO_WITH_AUDIO
        val quality = buildString {
            append(resolution)
            if (fps > 0) append(" · ${fps}fps")
            if (codec.isNotBlank()) append(" · $codec")
        }.ifBlank { "Video format" }
        return ExtractedFormat(
            id = "${kind.name.lowercase()}-$id-${format?.name.orEmpty()}",
            kind = kind,
            label = quality,
            url = url.orEmpty(),
            mimeType = format?.mimeType.orEmpty(),
            extension = format?.suffix.orEmpty(),
            width = width.takeIf { it > 0 },
            height = height.takeIf { it > 0 },
            frameRate = fps.takeIf { it > 0 },
            codec = codec.takeIf { it.isNotBlank() },
            bitrate = bitrate.takeIf { it > 0 }
        )
    }

    private fun AudioStream.toFormat(): ExtractedFormat {
        val format = format
        val language = audioTrackName?.takeIf { it.isNotBlank() } ?: audioLocale?.displayName
        val detail = listOfNotNull(quality.takeIf { it.isNotBlank() }, codec.takeIf { it.isNotBlank() }, language)
            .joinToString(" · ").ifBlank { "Audio format" }
        return ExtractedFormat(
            id = "audio-$id-${format?.name.orEmpty()}",
            kind = ExtractedFormatKind.AUDIO,
            label = detail,
            url = url.orEmpty(),
            mimeType = format?.mimeType.orEmpty(),
            extension = format?.suffix.orEmpty(),
            codec = codec.takeIf { it.isNotBlank() },
            bitrate = averageBitrate.takeIf { it > 0 },
            language = language
        )
    }

    private fun SubtitlesStream.toSubtitleOrNull(): ExtractedSubtitle? {
        val source = url ?: return null
        if (source.isBlank()) return null
        return ExtractedSubtitle(languageTag, displayLanguageName, isAutoGenerated, source, extension)
    }

    fun supportsUrl(url: String): Boolean {
        val parsed = runCatching { URL(url) }.getOrNull() ?: return false
        if (parsed.protocol != "https" || parsed.userInfo != null || parsed.host.isNullOrBlank()) return false
        initializeRuntime()
        return runCatching { NewPipe.getServiceByUrl(url) }.isSuccess
    }

    private fun initializeRuntime() = synchronized(initializationLock) {
        if (initialized.get()) return@synchronized
        NewPipe.init(UrlConnectionDownloader())
        initialized.set(true)
    }

    companion object {
        private val initializationLock = Any()
        private val initialized = AtomicBoolean(false)
    }
}

/** Minimal URLConnection transport for NewPipe's text/API requests. It never logs URLs or response bodies. */
private class UrlConnectionDownloader : Downloader() {
    override fun execute(request: Request): Response {
        val connection = (URL(request.url()).openConnection() as HttpURLConnection).apply {
            connectTimeout = 15_000
            readTimeout = 20_000
            instanceFollowRedirects = true
            requestMethod = request.httpMethod()
            val headers = request.headers()
            if (headers.keys.none { it.equals("User-Agent", ignoreCase = true) }) {
                setRequestProperty("User-Agent", "WAFF Android (NewPipeExtractor)")
            }
            if (headers.keys.none { it.equals("Accept-Encoding", ignoreCase = true) }) {
                setRequestProperty("Accept-Encoding", "gzip, deflate, identity")
            }
            headers.forEach { (name, values) -> values.forEach { addRequestProperty(name, it) } }
            request.dataToSend()?.let { body ->
                doOutput = true
                outputStream.use { it.write(body) }
            }
        }
        try {
            val status = connection.responseCode
            val raw = (if (status >= HttpURLConnection.HTTP_BAD_REQUEST) connection.errorStream else connection.inputStream)
            val encoding = connection.contentEncoding?.lowercase().orEmpty()
            val body = raw?.use { stream ->
                val decoded = when (encoding) {
                    "gzip" -> GZIPInputStream(stream)
                    "deflate" -> InflaterInputStream(stream)
                    else -> stream
                }
                decoded.use { input -> ByteArrayOutputStream().also { input.copyTo(it) }.toString(Charsets.UTF_8.name()) }
            }.orEmpty()
            val responseHeaders = connection.headerFields
                .filterKeys { it != null }
                .mapKeys { it.key!! }
            return Response(status, connection.responseMessage.orEmpty(), responseHeaders, body, connection.url.toString())
        } catch (e: IOException) {
            throw e
        } finally {
            connection.disconnect()
        }
    }
}
