package com.waff.app

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalClipboardManager
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.semantics.contentDescription
import androidx.compose.ui.semantics.semantics
import com.waff.app.platform.newpipe.ExtractedFormat
import com.waff.app.platform.newpipe.ExtractedFormatKind
import com.waff.app.platform.newpipe.ExtractedMediaInfo
import com.waff.app.platform.newpipe.ExtractedSubtitle

@Composable
internal fun ExtractedFormatsPanel(
    info: ExtractedMediaInfo,
    selectedId: String?, onSelect: (String) -> Unit,
    selectedVideoId: String?, onSelectVideo: (String) -> Unit,
    selectedAudioId: String?, onSelectAudio: (String) -> Unit,
    mergeSupported: Boolean, onMerge: () -> Unit,
    onSaveSubtitle: (ExtractedSubtitle) -> Unit,
    onSaveThumbnail: () -> Unit,
    alsoSaveThumbnail: Boolean,
    onAlsoSaveThumbnail: (Boolean) -> Unit
) {
    val clipboard = LocalClipboardManager.current
    Column(Modifier.fillMaxWidth().fillMaxHeight(.92f).verticalScroll(rememberScrollState()).padding(horizontal = 22.dp)) {
        Text("Choose quality", style = MaterialTheme.typography.headlineSmall, fontWeight = FontWeight.SemiBold)
        Text(info.title, style = MaterialTheme.typography.titleMedium, color = Muted, maxLines = 2)
        if (info.durationSeconds > 0) Text(formatDuration(info.durationSeconds), color = Muted, style = MaterialTheme.typography.labelSmall)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.padding(top = 10.dp)) {
            OutlinedButton(onClick = { clipboard.setText(androidx.compose.ui.text.AnnotatedString(info.title)) }) { Text("Copy title") }
            if (info.hashtags.isNotEmpty()) OutlinedButton(onClick = {
                clipboard.setText(androidx.compose.ui.text.AnnotatedString(info.hashtags.joinToString(" ") { "#$it" }))
            }) { Text("Copy hashtags") }
        }
        if (!info.thumbnailUrl.isNullOrBlank()) {
            Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                OutlinedButton(onClick = onSaveThumbnail) { Text("Download thumbnail only") }
                Spacer(Modifier.width(8.dp))
                Row(Modifier.weight(1f), verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(alsoSaveThumbnail, onAlsoSaveThumbnail)
                    Text("Also save with video", style = MaterialTheme.typography.bodySmall, color = Muted)
                }
            }
        }
        if (info.subtitles.isNotEmpty()) {
            Text("Subtitles", style = MaterialTheme.typography.titleSmall, fontWeight = FontWeight.Medium, modifier = Modifier.padding(top = 12.dp))
            Text("Choose languages to save", color = Muted, style = MaterialTheme.typography.labelSmall)
            info.subtitles.forEach { subtitle ->
                var enabled by remember(info.canonicalUrl, subtitle.languageTag) { mutableStateOf(false) }
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(enabled, { enabled = it })
                    Text("${subtitle.languageName}${if (subtitle.autoGenerated) " · auto" else ""}", modifier = Modifier.weight(1f), color = Paper, style = MaterialTheme.typography.bodySmall)
                    TextButton(onClick = { onSaveSubtitle(subtitle) }) { Text("Save") }
                }
            }
        }
        val hasSeparatePair = info.formats.any { it.kind == ExtractedFormatKind.VIDEO_ONLY } && info.formats.any { it.kind == ExtractedFormatKind.AUDIO }
        if (hasSeparatePair) Text(
            if (mergeSupported) "Separate video and audio tracks can be merged into one MKV."
            else "Separate tracks cannot be safely merged here. Choose a combined stream.",
            color = Muted, style = MaterialTheme.typography.labelSmall, modifier = Modifier.padding(top = 8.dp)
        )
        listOf(
            ExtractedFormatKind.VIDEO_WITH_AUDIO to "Video · with audio",
            ExtractedFormatKind.VIDEO_ONLY to "Video · no audio",
            ExtractedFormatKind.AUDIO to "Audio"
        ).forEach { (kind, title) ->
            val formats = info.formats.filter { it.kind == kind }
                .sortedWith(compareByDescending<ExtractedFormat> { it.height ?: 0 }
                    .thenByDescending { it.width ?: 0 }.thenByDescending { it.bitrate ?: 0 })
            if (formats.isNotEmpty()) {
                Text(title, style = MaterialTheme.typography.titleSmall, fontWeight = FontWeight.Medium, modifier = Modifier.padding(top = 14.dp, bottom = 4.dp))
                formats.forEach { format ->
                    val selected = when (kind) {
                        ExtractedFormatKind.VIDEO_ONLY -> selectedVideoId == format.id
                        ExtractedFormatKind.AUDIO -> selectedAudioId == format.id
                        else -> selectedId == format.id
                    }
                    val callback = when (kind) {
                        ExtractedFormatKind.VIDEO_ONLY -> onSelectVideo
                        ExtractedFormatKind.AUDIO -> onSelectAudio
                        else -> onSelect
                    }
                    FormatChoice(format, selected, callback)
                }
            }
        }
        if (hasSeparatePair && mergeSupported) Button(onClick = onMerge,
            enabled = selectedVideoId != null && selectedAudioId != null,
            modifier = Modifier.fillMaxWidth().padding(top = 12.dp),
            colors = ButtonDefaults.buttonColors(containerColor = Paper, contentColor = androidx.compose.ui.graphics.Color.Black)) {
            Text("Merge selected tracks")
        }
        Spacer(Modifier.height(24.dp))
    }
}

@Composable
private fun FormatChoice(format: ExtractedFormat, selected: Boolean, onSelect: (String) -> Unit) {
    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        RadioButton(selected, onClick = { onSelect(format.id) }, modifier = Modifier.semantics { contentDescription = format.label })
        Column(Modifier.weight(1f).padding(vertical = 5.dp)) {
            val dimensions = if (format.width != null && format.height != null) "${format.width} × ${format.height}" else null
            Text(listOfNotNull(dimensions, format.label).distinct().joinToString(" · "), color = Paper, style = MaterialTheme.typography.bodyMedium, maxLines = 2)
            val details = listOfNotNull(format.codec, format.mimeType, format.bitrate?.takeIf { it > 0 }?.let { "${it / 1000} kb/s" }, format.fileSizeBytes?.let(::formatBytes)).joinToString(" · ")
            Text(details.ifBlank { "Size unavailable" }, color = Muted, style = MaterialTheme.typography.labelSmall)
        }
    }
}

private fun formatBytes(bytes: Long): String {
    val mib = bytes.toDouble() / (1024 * 1024)
    return if (mib >= 1024) "%.2f GiB".format(mib / 1024) else "%.1f MiB".format(mib)
}

private fun formatDuration(seconds: Long): String {
    val hours = seconds / 3600; val minutes = (seconds % 3600) / 60; val remainingSeconds = seconds % 60
    return if (hours > 0) "%d:%02d:%02d".format(hours, minutes, remainingSeconds) else "%d:%02d".format(minutes, remainingSeconds)
}
