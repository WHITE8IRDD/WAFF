package com.waff.app

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.RadioButton
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import androidx.compose.ui.semantics.contentDescription
import androidx.compose.ui.semantics.semantics
import com.waff.app.platform.newpipe.ExtractedFormat
import com.waff.app.platform.newpipe.ExtractedFormatKind
import com.waff.app.platform.newpipe.ExtractedMediaInfo
import com.waff.app.platform.newpipe.ExtractedSubtitle

@Composable
internal fun ExtractedFormatsPanel(
    info: ExtractedMediaInfo,
    selectedId: String?,
    onSelect: (String) -> Unit,
    selectedVideoId: String?,
    onSelectVideo: (String) -> Unit,
    selectedAudioId: String?,
    onSelectAudio: (String) -> Unit,
    onMerge: () -> Unit,
    onSaveSubtitle: (ExtractedSubtitle) -> Unit,
    onSaveThumbnail: () -> Unit
) {
    Column(Modifier.fillMaxWidth().heightIn(max = 300.dp).verticalScroll(rememberScrollState())) {
        Text(info.title, style = MaterialTheme.typography.titleMedium, color = Paper, maxLines = 2)
        if (info.durationSeconds > 0) Text(formatDuration(info.durationSeconds), color = Muted, style = MaterialTheme.typography.labelSmall)
        if (!info.thumbnailUrl.isNullOrBlank()) {
            androidx.compose.material3.OutlinedButton(onClick = onSaveThumbnail) { Text("Save thumbnail") }
        }
        Spacer(Modifier.height(8.dp))
        if (info.formats.isEmpty()) {
            Text("The extractor returned no downloadable formats.", color = Muted, style = MaterialTheme.typography.bodySmall)
        }
        if (info.subtitles.isNotEmpty()) {
            Text("Subtitles", color = Paper, style = MaterialTheme.typography.labelLarge, modifier = Modifier.padding(top = 8.dp))
            info.subtitles.forEach { subtitle ->
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.SpaceBetween) {
                    Text("${subtitle.languageName}${if (subtitle.autoGenerated) " · auto" else ""}", color = Muted, style = MaterialTheme.typography.bodySmall, modifier = Modifier.weight(1f))
                    androidx.compose.material3.OutlinedButton(onClick = { onSaveSubtitle(subtitle) }) { Text("Save") }
                }
            }
        }
        val hasSeparatePair = info.formats.any { it.kind == ExtractedFormatKind.VIDEO_ONLY } && info.formats.any { it.kind == ExtractedFormatKind.AUDIO }
        if (hasSeparatePair) {
            Text("Choose separate tracks to mux into one MKV file.", color = Muted, style = MaterialTheme.typography.labelSmall, modifier = Modifier.padding(top = 6.dp))
        }
        listOf(
            ExtractedFormatKind.VIDEO_WITH_AUDIO to "Video with audio",
            ExtractedFormatKind.VIDEO_ONLY to "Video only · no audio",
            ExtractedFormatKind.AUDIO to "Audio only"
        ).forEach { (kind, title) ->
            val formats = info.formats.filter { it.kind == kind }
            if (formats.isNotEmpty()) {
                Text(title, style = MaterialTheme.typography.labelLarge, color = Paper, modifier = Modifier.padding(top = 8.dp, bottom = 2.dp))
                formats.forEach { format ->
                    val isSelected = when (kind) {
                        ExtractedFormatKind.VIDEO_ONLY -> selectedVideoId == format.id
                        ExtractedFormatKind.AUDIO -> selectedAudioId == format.id
                        else -> selectedId == format.id
                    }
                    val callback = when (kind) {
                        ExtractedFormatKind.VIDEO_ONLY -> onSelectVideo
                        ExtractedFormatKind.AUDIO -> onSelectAudio
                        else -> onSelect
                    }
                    FormatChoice(format, isSelected, callback)
                }
            }
        }
        if (hasSeparatePair) {
            androidx.compose.material3.Button(onClick = onMerge, enabled = selectedVideoId != null && selectedAudioId != null,
                modifier = Modifier.fillMaxWidth().padding(top = 8.dp), colors = androidx.compose.material3.ButtonDefaults.buttonColors(containerColor = Paper, contentColor = androidx.compose.ui.graphics.Color.Black)) {
                Text("Merge selected tracks")
            }
        }
    }
}

@Composable
private fun FormatChoice(format: ExtractedFormat, selected: Boolean, onSelect: (String) -> Unit) {
    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        RadioButton(selected = selected, onClick = { onSelect(format.id) }, modifier = Modifier.semantics { contentDescription = format.label })
        Column(Modifier.weight(1f).padding(vertical = 4.dp)) {
            Text(format.label, color = Paper, style = MaterialTheme.typography.bodySmall, maxLines = 2)
            val details = listOfNotNull(format.mimeType, format.bitrate?.takeIf { it > 0 }?.let { "${it / 1000} kb/s" }).joinToString(" · ")
            if (details.isNotBlank()) Text(details, color = Muted, style = MaterialTheme.typography.labelSmall)
        }
    }
}

private fun formatDuration(seconds: Long): String {
    val hours = seconds / 3600
    val minutes = (seconds % 3600) / 60
    val remainingSeconds = seconds % 60
    return if (hours > 0) "%d:%02d:%02d".format(hours, minutes, remainingSeconds)
    else "%d:%02d".format(minutes, remainingSeconds)
}

